#!/usr/bin/env bun
/**
 * scripts/platform-docs-snapshot.ts
 *
 * Vendors the platform docs (PLD-2.1). On each platform release the receiver
 * (.github/workflows/platform-release.yml) checks out app-vitals/agent at the
 * release tag and runs this script to copy that tag's `docs/*.md` into
 * `docs/platform/`, a read-only snapshot. Every snapshot file starts with a
 * generated header linking its source in app-vitals/agent at that tag.
 * scripts/platform-docs-guard.ts blocks hand edits to the directory.
 *
 * The directory is rewritten wholesale: files the release no longer ships are
 * removed, so the snapshot always equals the tagged docs.
 *
 * Usage:
 *   bun scripts/platform-docs-snapshot.ts <version> <platform-checkout> [--root <dir>]
 *
 * Exit codes: 0 snapshot written or already current, 1 invalid version or no
 * docs found in the checkout, 2 usage.
 */

import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import { isStrictSemver } from "./platform-release-bump.ts";

export const PLATFORM_REPO = "app-vitals/agent";
/** Snapshot location, repo-relative. */
export const SNAPSHOT_DIR = "docs/platform";
/** Docs directory inside the platform repository. */
export const SOURCE_DOCS_DIR = "docs";
/** First line of every snapshot file; the guard and tests key off it. */
export const HEADER_MARKER = "<!-- GENERATED: platform docs snapshot";

/** Link to a doc in app-vitals/agent at the release tag `v<version>`. */
export function sourceUrl(version: string, file: string): string {
  return `https://github.com/${PLATFORM_REPO}/blob/v${version}/${SOURCE_DOCS_DIR}/${file}`;
}

/** The generated header, ending with a blank line before the doc body. */
export function header(version: string, file: string): string {
  return [
    `${HEADER_MARKER}. Do not edit. -->`,
    `<!-- Source: ${sourceUrl(version, file)} -->`,
    `<!-- Regenerated by .github/workflows/platform-release.yml (scripts/platform-docs-snapshot.ts). -->`,
    "",
    "",
  ].join("\n");
}

/** Snapshot content for one source doc. */
export function renderSnapshot(
  version: string,
  file: string,
  body: string,
): string {
  return header(version, file) + body;
}

/** Markdown docs shipped at the top level of the platform docs dir, sorted. */
export function listSourceDocs(platformRoot: string): string[] {
  const dir = join(platformRoot, SOURCE_DOCS_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(".md"))
    .map((e) => e.name)
    .sort();
}

export interface SnapshotResult {
  /** Files written, new or changed. */
  written: string[];
  /** Files removed because the release no longer ships them. */
  removed: string[];
  /** Files already identical to the release. */
  unchanged: string[];
}

/** Rewrites `<root>/docs/platform/` from the platform checkout's docs. */
export function snapshotDocs(
  root: string,
  platformRoot: string,
  version: string,
): SnapshotResult {
  if (!isStrictSemver(version)) {
    throw new Error(`not a strict X.Y.Z version: ${JSON.stringify(version)}`);
  }
  const sources = listSourceDocs(platformRoot);
  if (sources.length === 0) {
    throw new Error(`no ${SOURCE_DOCS_DIR}/*.md found in ${platformRoot}`);
  }
  const out = join(root, SNAPSHOT_DIR);
  mkdirSync(out, { recursive: true });
  const result: SnapshotResult = { written: [], removed: [], unchanged: [] };
  for (const file of sources) {
    const next = renderSnapshot(
      version,
      file,
      readFileSync(join(platformRoot, SOURCE_DOCS_DIR, file), "utf8"),
    );
    const path = join(out, file);
    if (existsSync(path) && readFileSync(path, "utf8") === next) {
      result.unchanged.push(file);
    } else {
      writeFileSync(path, next);
      result.written.push(file);
    }
  }
  for (const entry of readdirSync(out, { withFileTypes: true })) {
    if (!sources.includes(entry.name)) {
      rmSync(join(out, entry.name), { recursive: true, force: true });
      result.removed.push(entry.name);
    }
  }
  result.removed.sort();
  return result;
}

function main(argv: string[]): number {
  let root = process.cwd();
  const positional: string[] = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--root") {
      const dir = argv[++i];
      if (!dir) {
        console.error("--root needs a directory");
        return 2;
      }
      root = resolve(dir);
    } else {
      positional.push(argv[i]);
    }
  }
  if (positional.length !== 2) {
    console.error(
      "usage: platform-docs-snapshot.ts <version> <platform-checkout> [--root <dir>]",
    );
    return 2;
  }
  const [version, platformRoot] = positional;
  if (!isStrictSemver(version)) {
    console.error(
      `ERROR: refusing platform release version ${JSON.stringify(version)}: expected strict X.Y.Z`,
    );
    return 1;
  }
  try {
    const r = snapshotDocs(root, resolve(platformRoot), version);
    console.log(
      `Platform docs ${version}: ${r.written.length} written, ${r.removed.length} removed, ${r.unchanged.length} unchanged`,
    );
    return 0;
  } catch (err) {
    console.error(`ERROR: ${(err as Error).message}`);
    return 1;
  }
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
