#!/usr/bin/env bun
/**
 * scripts/check-import-boundary.ts
 *
 * Import-boundary gate. Walks every TypeScript source in runtime/, admin/,
 * lib/ and agent-types/ plus the root index.ts, and fails on any module
 * specifier that leaves the repository:
 *
 *   - relative specifiers must resolve to a file inside the repository
 *   - @app-vitals/agent-runtime/*, @app-vitals/agent-lib/* and
 *     @app-vitals/agent-admin[/*] must resolve to a source file in runtime/,
 *     lib/ or admin/
 *   - the pre-extraction workspace scope is not allowed
 *
 * npm packages and node:/bun: builtins are not edges.
 *
 * Usage: bun scripts/check-import-boundary.ts [root]
 */

import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

/** The workspace scope used before the packages moved to @app-vitals/. */
const LEGACY_SCOPE = `@${"shipwright"}/`;

const SCAN_DIRS = ["runtime", "admin", "lib", "agent-types", "scripts"];
const SCAN_FILES = ["index.ts"];
const SKIP_DIRS = new Set(["node_modules", "dist", "client", "e2e"]);
/** Tests that carry import specifiers as string fixtures, not real imports. */
const FIXTURE_FILES = new Set(["import-boundary.unit.test.ts"]);
const SOURCE = /\.(?:ts|tsx|js|mjs|cjs)$/;
const RESOLVE_SUFFIXES = ["", ".ts", ".tsx", ".js", ".json", "/index.ts"];

const SPECIFIER_PATTERNS = [
  /\b(?:import|export)\s+(?:type\s+)?(?:[^'"`;]*?\s+from\s+)?["']([^"']+)["']/g,
  /\bimport\(\s*["']([^"']+)["']\s*\)/g,
  /\brequire\(\s*["']([^"']+)["']\s*\)/g,
  /\bmock\.module\(\s*["']([^"']+)["']/g,
];

export interface BoundaryViolation {
  file: string;
  specifier: string;
  reason: string;
}

export function extractSpecifiers(source: string): string[] {
  const found = new Set<string>();
  for (const pattern of SPECIFIER_PATTERNS) {
    for (const m of source.matchAll(pattern)) found.add(m[1]);
  }
  return [...found];
}

function walk(dir: string, out: string[]): void {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (SOURCE.test(name) && !FIXTURE_FILES.has(name)) out.push(full);
  }
}

function resolves(base: string): boolean {
  return RESOLVE_SUFFIXES.some((suffix) => {
    const candidate = base + suffix;
    return existsSync(candidate) && statSync(candidate).isFile();
  });
}

function inExportsMap(root: string, sub: string): boolean {
  const pkgPath = join(root, "admin", "package.json");
  if (!existsSync(pkgPath)) return false;
  const exportsMap = (
    JSON.parse(readFileSync(pkgPath, "utf8")) as {
      exports?: Record<string, unknown>;
    }
  ).exports;
  return Object.keys(exportsMap ?? {}).some((key) =>
    key.endsWith("*")
      ? `./${sub}`.startsWith(key.slice(0, -1))
      : key === `./${sub}`,
  );
}

function checkSpecifier(
  root: string,
  file: string,
  spec: string,
): string | null {
  if (spec.startsWith(LEGACY_SCOPE)) {
    return `the ${LEGACY_SCOPE} scope does not exist in this repository`;
  }
  if (spec.startsWith(".")) {
    const target = resolve(dirname(file), spec);
    const rel = relative(root, target);
    if (rel.startsWith("..")) return "resolves outside the repository";
    // Generated by `prisma generate`; never committed.
    if (rel.startsWith(join("admin", "prisma", "client"))) return null;
    return resolves(target) ? null : "does not resolve to a file";
  }
  const workspace = /^@app-vitals\/agent-(runtime|lib|admin)(?:\/(.+))?$/.exec(
    spec,
  );
  if (workspace) {
    const [, pkg, sub] = workspace;
    if (!sub) {
      return pkg === "admin" ? null : "bare workspace import has no entry";
    }
    if (pkg === "admin") {
      return inExportsMap(root, sub) ? null : "not in admin's exports map";
    }
    return resolves(join(root, pkg, sub)) ? null : "workspace module not found";
  }
  return null;
}

/** Returns every import edge that leaves the repository rooted at `root`. */
export function checkBoundary(root: string): BoundaryViolation[] {
  const files: string[] = [];
  for (const dir of SCAN_DIRS) walk(join(root, dir), files);
  for (const f of SCAN_FILES) {
    if (existsSync(join(root, f))) files.push(join(root, f));
  }
  const violations: BoundaryViolation[] = [];
  for (const file of files.sort()) {
    for (const spec of extractSpecifiers(readFileSync(file, "utf8"))) {
      const reason = checkSpecifier(root, file, spec);
      if (reason) {
        violations.push({
          file: relative(root, file),
          specifier: spec,
          reason,
        });
      }
    }
  }
  return violations;
}

if (import.meta.main) {
  const root = resolve(process.argv[2] ?? ".");
  const violations = checkBoundary(root);
  if (violations.length > 0) {
    for (const v of violations) {
      console.error(`${v.file}: "${v.specifier}" ${v.reason}`);
    }
    console.error(`\n${violations.length} import-boundary violation(s)`);
    process.exit(1);
  }
  console.log("import boundary clean");
}
